# -*- coding: utf-8 -*-
"""从排版器导出的 JSON 生成 doppler_layout.h，并把同一份写回 layout_editor.html。

用法：python gen_layout.py <json 路径>
不改固件里任何别的文件；排版器的 defaultModel 与这份逐条一致是 verify_layout.py 的前提。
"""
import io
import json
import sys

NAMES = ['READY', 'RUN', 'DONE', 'EMPTY', 'CLOCK', 'CALIBRATE',
         'INFO', 'PRE-LISTEN', 'POST-LISTEN']
FONT = {'tiny': 0, 'small': 1, 'bold': 2, 'big': 3, 'bar': 4}
ALIGN = {'left': 0, 'center': 1, 'right': 2}

src = sys.argv[1]
stamp = sys.argv[2] if len(sys.argv) > 2 else '2026-11-02'
model = json.load(io.open(src, encoding='utf-8'))
total = sum(len(p) for p in model)

# ---- doppler_layout.h ----
out = ['/* generated by layout_editor.html —— 版面由操作员在排版器里定稿（%s），' % stamp,
       ' * 共 %d 条 / %d 页。改坐标请回 PC工具/多普勒工具/layout_editor.html 里排，' % (total, len(model)),
       ' * 不要手改这里：verify_layout.py 会拿编辑器 defaultModel 跟这份逐条比对。 */',
       'static const dph_item_t dph_layout[] =', '{']
for i, page in enumerate(model):
    out.append('    /* %s */' % NAMES[i])
    for it in page:
        out.append('    { %d, %d, %d, %d, %d, "%s" },'
                   % (i, FONT[it['font']], ALIGN[it['align']], it['x'], it['y'], it['text']))
out += ['};', '',
        '#define DPH_ITEM_COUNT ((uint8_t)(sizeof(dph_layout) / sizeof(dph_layout[0])))', '']
io.open('../../固件源码/uvk1-v6.3.0/App/app/doppler_layout.h', 'w',
        encoding='utf-8', newline='').write('\n'.join(out))

# ---- layout_editor.html 的 defaultModel() ----
def q(t):
    return "'" + t + "'" if "'" not in t else '"' + t + '"'

lines = ['function defaultModel(){', '  return [']
for i, page in enumerate(model):
    lines.append('    /* %d %s */' % (i, NAMES[i]))
    lines.append('    [')
    for it in page:
        lines.append("      {text: %s, font: '%s', x: %d, y: %d, align: '%s'},"
                     % (q(it['text']), it['font'], it['x'], it['y'], it['align']))
    lines.append('    ],')
lines += ['  ];', '}']
block = '\n'.join(lines)

p = 'layout_editor.html'
s = io.open(p, encoding='utf-8').read()
start = s.index('function defaultModel(){')
end = s.index('\n  ];\n}', start) + len('\n  ];\n}')
io.open(p, 'w', encoding='utf-8', newline='').write(s[:start] + block + s[end:])
print('ok: %d 条 / %d 页' % (total, len(model)))
