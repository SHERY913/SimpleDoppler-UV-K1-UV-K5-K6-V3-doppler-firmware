export interface FlatVar extends VarLeaf {
  group: string
}

export function flatVars(): FlatVar[] {
  const out: FlatVar[] = []
  const walk = (g: VarGroup): void => {
    for (const l of g.leaves) out.push({ ...l, group: g.label })
    for (const c of g.children ?? []) walk(c)
  }
  for (const g of VAR_TREE) walk(g)
  return out
}

export const EXPR_SUGGEST_FIELDS = flatVars().map((v) => v.path)
